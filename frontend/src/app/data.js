function treeToGraph(treeData, position = { x: 50, y: 100 }, parentID = null, nodes = [], edges = [], depth = 0, verticalSpacing = 100) {
 try{
  treeData.forEach((node, index) => {
    processNode(node, position, parentID, nodes, edges, depth, verticalSpacing);
  });

  return [nodes, edges];
 }
 catch(e){
  return null
 }

}

function processNode(node, position, parentID, nodes, edges, depth, verticalSpacing) {
  const { x, y } = position;
  const nodeID = (nodes.length + 1).toString();

  
  const newNode = {
    id: nodeID,
    position: { x, y },
    data: { label: node.title }
  };
  nodes.push(newNode);

  
  if (parentID !== null) {
    const newEdge = {
      id: `e${parentID}-${nodeID}`,
      source: parentID,
      target: nodeID,
      
    };
    edges.push(newEdge);
  }

  
  let nextY = y;
  let maxWidth = x;

  
  node.children?.forEach((child, index) => {
    const subtreeHeight = getSubtreeHeight(child, verticalSpacing);
    const childY = index === 0 ? nextY : nextY + subtreeHeight / 2;
    const childX = x + 250;

    processNode(child, { x: childX, y: childY }, nodeID, nodes, edges, depth + 1, verticalSpacing);

    nextY += subtreeHeight;
    maxWidth = Math.max(maxWidth, childX);
  });

  
  if (node.children?.length > 0) {
    maxWidth += 150;
  }
}

function getSubtreeHeight(node, baseHeight) {
  if (!node.children || node.children.length === 0) {
    return baseHeight;
  }
  let totalHeight = 0;
  node.children.forEach(child => {
    totalHeight += getSubtreeHeight(child, baseHeight);
  });
  return totalHeight;
}
 
